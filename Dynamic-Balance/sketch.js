// ============================================================
// FIREWORKS - FINAL
// p5.js + Matter.js
//
// - 다양한 크기의 불꽃
// - 한 번에 1개, 가끔 2개
// - 벽과 바닥에 충돌
// - 벽/바닥에 가까워질수록 꼬리가 짧아짐
// - 바닥에 불꽃이 쌓임
// - 일정량 이상 쌓이면 오래된 불꽃부터 사라짐
// - 전체적인 화려함을 살짝 정돈
// ============================================================

const Engine = Matter.Engine;
const World = Matter.World;
const Bodies = Matter.Bodies;
const Body = Matter.Body;

let engine;
let world;

let fireworks = [];

let floor;
let leftWall;
let rightWall;

let nextFirework = 20;

// ============================================================
// 바닥에 유지할 최대 불꽃 개수
// ============================================================

let maxLandedParticles = 55;

// ============================================================
// 불꽃 색상
// ============================================================

let colors = [
  "#ff4b45", // 빨강
  "#ff7d9d", // 분홍
  "#ffd84a", // 노랑
  "#ffb65c", // 주황
  "#fff4ef", // 흰색
  "#ffb6c9", // 연분홍
];

// ============================================================
// SETUP
// ============================================================

function setup() {
  createCanvas(windowWidth, windowHeight);

  engine = Engine.create();

  world = engine.world;

  // 중력
  world.gravity.y = 0.9;

  // ==========================================================
  // 바닥
  // ==========================================================

  floor = Bodies.rectangle(width / 2, height - 8, width + 100, 30, {
    isStatic: true,
    restitution: 0.25,
    friction: 0.25,
  });

  // ==========================================================
  // 왼쪽 벽
  // ==========================================================

  leftWall = Bodies.rectangle(-8, height / 2, 30, height + 100, {
    isStatic: true,
    restitution: 0.6,
    friction: 0.05,
  });

  // ==========================================================
  // 오른쪽 벽
  // ==========================================================

  rightWall = Bodies.rectangle(width + 8, height / 2, 30, height + 100, {
    isStatic: true,
    restitution: 0.6,
    friction: 0.05,
  });

  World.add(world, [floor, leftWall, rightWall]);

  noStroke();
}

// ============================================================
// DRAW
// ============================================================

function draw() {
  background("#080914");

  // 물리 엔진 실행
  Engine.update(engine);

  // ==========================================================
  // 자동으로 폭죽 생성
  // ==========================================================

  if (frameCount >= nextFirework) {
    createFirework();

    // 기존 생성 빈도 유지
    nextFirework = frameCount + int(random(55, 80));
  }

  // ==========================================================
  // 바닥에 너무 많이 쌓였는지 확인
  // ==========================================================

  checkLandedParticles();

  // ==========================================================
  // 모든 불꽃 업데이트
  // ==========================================================

  for (let i = fireworks.length - 1; i >= 0; i--) {
    fireworks[i].update();

    fireworks[i].display();

    // ========================================================
    // 완전히 사라진 불꽃 제거
    // ========================================================

    if (fireworks[i].isDead()) {
      World.remove(world, fireworks[i].body);

      fireworks.splice(i, 1);
    }
  }
}

// ============================================================
// 폭죽 생성
// ============================================================

function createFirework() {
  // ==========================================================
  // 한 번에 터지는 폭죽 개수
  //
  // 78% = 1개
  // 22% = 2개
  // ==========================================================

  let burstCount = 1;

  if (random() < 0.22) {
    burstCount = 2;
  }

  // ==========================================================
  // 폭죽 생성
  // ==========================================================

  for (let b = 0; b < burstCount; b++) {
    // ========================================================
    // 터지는 위치
    // ========================================================

    let x = random(width * 0.15, width * 0.85);

    let y = random(height * 0.15, height * 0.42);

    // ========================================================
    // 폭죽 크기 결정
    //
    // 30% = 작은 폭죽
    // 52% = 중간 폭죽
    // 18% = 큰 폭죽
    // ========================================================

    let sizeType = random();

    let burstScale;

    // 작은 불꽃
    if (sizeType < 0.3) {
      burstScale = random(0.75, 0.88);

      // 중간 불꽃
    } else if (sizeType < 0.82) {
      burstScale = random(0.9, 1.08);

      // 큰 불꽃
    } else {
      burstScale = random(1.15, 1.3);
    }

    // ========================================================
    // 폭죽 기본 색상
    // ========================================================

    let mainColor = random(colors);

    // ========================================================
    // 크기에 따라 가지 수 조절
    // ========================================================

    let amount = int(random(9, 14) * burstScale);

    // 너무 적거나 많지 않도록 제한
    amount = constrain(amount, 8, 16);

    // ========================================================
    // 각각의 불꽃 생성
    // ========================================================

    for (let i = 0; i < amount; i++) {
      // ======================================================
      // 원형으로 퍼지는 방향
      // ======================================================

      let angle = map(i, 0, amount, 0, TWO_PI);

      // 완벽한 원이 되지 않도록 살짝 불규칙하게
      angle += random(-0.14, 0.14);

      // ======================================================
      // 폭발 속도
      //
      // 큰 폭죽은 더 넓게,
      // 작은 폭죽은 더 작게 퍼짐
      // ======================================================

      let speed = random(9, 14) * burstScale;

      // 일부 불꽃만 살짝 더 길게
      if (random() < 0.18) {
        speed *= 1.2;
      }

      let vx = cos(angle) * speed;

      let vy = sin(angle) * speed;

      // ======================================================
      // 색상
      // ======================================================

      let particleColor = mainColor;

      // 가끔만 다른 색이 섞임
      if (random() < 0.1) {
        particleColor = random(colors);
      }

      // ======================================================
      // 불꽃 생성
      // ======================================================

      let particle = new FireworkParticle(x, y, vx, vy, particleColor);

      // ======================================================
      // 폭죽 크기에 따라
      // 머리 크기도 살짝 조절
      // ======================================================

      particle.size *= map(burstScale, 0.75, 1.3, 0.9, 1.1);

      // ======================================================
      // 폭죽 크기에 따라
      // 꼬리 길이도 살짝 조절
      // ======================================================

      particle.maxTrail = int(
        particle.maxTrail * map(burstScale, 0.75, 1.3, 0.9, 1.1),
      );

      fireworks.push(particle);
    }
  }
}

// ============================================================
// 바닥에 쌓인 불꽃 확인
// ============================================================

function checkLandedParticles() {
  let landed = [];

  // ==========================================================
  // 바닥에 정착한 불꽃만 찾기
  // ==========================================================

  for (let i = 0; i < fireworks.length; i++) {
    if (fireworks[i].landed && !fireworks[i].fading) {
      landed.push(fireworks[i]);
    }
  }

  // ==========================================================
  // 일정 개수 이상 쌓이면
  // 오래된 불꽃부터 사라짐
  // ==========================================================

  if (landed.length > maxLandedParticles) {
    let amountToRemove = landed.length - maxLandedParticles;

    for (let i = 0; i < amountToRemove; i++) {
      landed[i].fading = true;
    }
  }
}

// ============================================================
// 불꽃 클래스
// ============================================================

class FireworkParticle {
  constructor(x, y, vx, vy, col) {
    this.col = col;

    // ========================================================
    // 불꽃 머리 크기
    // ========================================================

    this.size = random(7, 11);

    // ========================================================
    // 지나온 위치
    // ========================================================

    this.trail = [];

    // ========================================================
    // 최대 꼬리 길이
    // ========================================================

    this.maxTrail = int(random(12, 19));

    // ========================================================
    // 바닥에 정착했는지
    // ========================================================

    this.landed = false;

    // ========================================================
    // 사라지는 중인지
    // ========================================================

    this.fading = false;

    // ========================================================
    // 투명도
    // ========================================================

    this.alpha = 255;

    // ========================================================
    // Matter.js 물리 오브젝트
    // ========================================================

    this.body = Bodies.circle(x, y, this.size / 2, {
      // 튕기는 정도
      restitution: random(0.35, 0.5),

      // 마찰
      friction: 0.15,

      // 정지 마찰
      frictionStatic: 0.4,

      // 공기 저항
      frictionAir: random(0.004, 0.008),

      density: 0.0015,
    });

    World.add(world, this.body);

    // ========================================================
    // 처음 폭발 속도
    // ========================================================

    Body.setVelocity(this.body, {
      x: vx,
      y: vy,
    });
  }

  // ==========================================================
  // UPDATE
  // ==========================================================

  update() {
    let pos = this.body.position;

    let speed = this.body.speed;

    // ========================================================
    // 움직일 때 지나온 위치 저장
    // ========================================================

    if (frameCount % 2 === 0 && speed > 1 && !this.landed) {
      this.trail.push({
        x: pos.x,
        y: pos.y,
      });
    }

    // ========================================================
    // 바닥까지 거리
    // ========================================================

    let distanceToFloor = height - pos.y;

    // ========================================================
    // 왼쪽 벽까지 거리
    // ========================================================

    let distanceToLeftWall = pos.x;

    // ========================================================
    // 오른쪽 벽까지 거리
    // ========================================================

    let distanceToRightWall = width - pos.x;

    // ========================================================
    // 가장 가까운 경계까지의 거리
    // ========================================================

    let distanceToBoundary = min(
      distanceToFloor,
      distanceToLeftWall,
      distanceToRightWall,
    );

    distanceToBoundary = max(0, distanceToBoundary);

    // ========================================================
    // 이 거리부터 꼬리가 줄어듦
    // ========================================================

    let shrinkDistance = min(width, height) * 0.22;

    // 기본적으로 최대 꼬리 길이
    let currentTrailLength = this.maxTrail;

    // ========================================================
    // 벽이나 바닥에 가까워질수록
    // 꼬리가 점점 짧아짐
    // ========================================================

    if (distanceToBoundary < shrinkDistance) {
      currentTrailLength = int(
        map(
          distanceToBoundary,

          0,
          shrinkDistance,

          1,
          this.maxTrail,

          true,
        ),
      );
    }

    // ========================================================
    // 바닥 근처에서 속도가 느려지면
    // 정착한 것으로 판단
    // ========================================================

    if (pos.y > height - 45 && speed < 0.8) {
      this.landed = true;

      // 정착하면 꼬리 제거
      currentTrailLength = 0;
    }

    // ========================================================
    // 거의 멈추면 꼬리 제거
    // ========================================================

    if (speed < 0.7) {
      currentTrailLength = 0;
    }

    // ========================================================
    // 오래된 꼬리 제거
    // ========================================================

    while (this.trail.length > currentTrailLength) {
      this.trail.shift();
    }

    // ========================================================
    // 바닥에 너무 많이 쌓여
    // 사라지는 대상으로 지정된 경우
    // ========================================================

    if (this.fading) {
      // 천천히 투명해짐
      this.alpha -= 7;

      // 크기도 살짝 작아짐
      this.size *= 0.985;
    }
  }

  // ==========================================================
  // DISPLAY
  // ==========================================================

  display() {
    let pos = this.body.position;

    // ========================================================
    // 1. 불꽃 꼬리
    // ========================================================

    if (this.trail.length > 2) {
      noFill();

      drawingContext.shadowBlur = 6;

      drawingContext.shadowColor = this.col;

      for (let i = 1; i < this.trail.length; i++) {
        let p1 = this.trail[i - 1];

        let p2 = this.trail[i];

        // ====================================================
        // 꼬리 끝은 얇고
        // 머리 쪽으로 갈수록 굵게
        // ====================================================

        let thickness = map(
          i,
          0,
          this.trail.length,

          0.4,
          this.size * 0.7,
        );

        // ====================================================
        // 꼬리 끝은 흐리고
        // 머리 쪽으로 갈수록 선명하게
        // ====================================================

        let trailAlpha = map(
          i,
          0,
          this.trail.length,

          20,
          this.alpha * 0.85,
        );

        stroke(colorWithAlpha(this.col, trailAlpha));

        strokeWeight(thickness);

        strokeCap(ROUND);

        line(p1.x, p1.y, p2.x, p2.y);
      }
    }

    // ========================================================
    // 2. 둥근 불꽃 머리
    // ========================================================

    noStroke();

    drawingContext.shadowBlur = 8;

    drawingContext.shadowColor = this.col;

    fill(colorWithAlpha(this.col, this.alpha));

    circle(pos.x, pos.y, this.size);

    // ========================================================
    // 3. 가운데 밝은 부분
    // ========================================================

    fill(255, 245, 235, this.alpha * 0.78);

    circle(pos.x, pos.y, this.size * 0.32);

    drawingContext.shadowBlur = 0;
  }

  // ==========================================================
  // 완전히 투명해지면 삭제
  // ==========================================================

  isDead() {
    return this.alpha <= 0;
  }
}

// ============================================================
// 색상 + 투명도
// ============================================================

function colorWithAlpha(hex, alpha) {
  let c = color(hex);

  c.setAlpha(constrain(alpha, 0, 255));

  return c;
}

// ============================================================
// WINDOW RESIZE
// ============================================================

function windowResized() {
  resizeCanvas(windowWidth, windowHeight);

  // ==========================================================
  // 기존 경계 제거
  // ==========================================================

  World.remove(world, floor);

  World.remove(world, leftWall);

  World.remove(world, rightWall);

  // ==========================================================
  // 바닥 다시 생성
  // ==========================================================

  floor = Bodies.rectangle(width / 2, height - 8, width + 100, 30, {
    isStatic: true,

    restitution: 0.25,

    friction: 0.25,
  });

  // ==========================================================
  // 왼쪽 벽 다시 생성
  // ==========================================================

  leftWall = Bodies.rectangle(-8, height / 2, 30, height + 100, {
    isStatic: true,

    restitution: 0.6,

    friction: 0.05,
  });

  // ==========================================================
  // 오른쪽 벽 다시 생성
  // ==========================================================

  rightWall = Bodies.rectangle(width + 8, height / 2, 30, height + 100, {
    isStatic: true,

    restitution: 0.6,

    friction: 0.05,
  });

  World.add(world, [floor, leftWall, rightWall]);
}
